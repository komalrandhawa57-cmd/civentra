DECLARE
    object_count NUMBER;
    constraint_count NUMBER;
    duplicate_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'INVOICES';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE invoices (
            invoice_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            invoice_number VARCHAR2(60) NOT NULL UNIQUE,
            citizen_id NUMBER NOT NULL,
            provider_id NUMBER,
            invoice_type VARCHAR2(30) NOT NULL,
            status VARCHAR2(20) NOT NULL,
            subtotal NUMBER(12,2) DEFAULT 0 NOT NULL,
            tax NUMBER(12,2) DEFAULT 0 NOT NULL,
            total_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
            amount_paid NUMBER(12,2) DEFAULT 0 NOT NULL,
            balance_due NUMBER(12,2) DEFAULT 0 NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT fk_invoice_citizen FOREIGN KEY (citizen_id) REFERENCES users(user_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'INVOICE_LINE_ITEMS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE invoice_line_items (
            line_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            invoice_id NUMBER NOT NULL,
            item_description VARCHAR2(1000) NOT NULL,
            quantity NUMBER(8,0) DEFAULT 1 NOT NULL,
            unit_price NUMBER(12,2) NOT NULL,
            total_price NUMBER(12,2) NOT NULL,
            CONSTRAINT fk_invoice_line_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_ESTIMATES';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_estimates (
            estimate_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            request_id NUMBER NOT NULL,
            provider_id NUMBER NOT NULL,
            citizen_id NUMBER NOT NULL,
            description VARCHAR2(1000) NOT NULL,
            subtotal NUMBER(12,2) NOT NULL,
            tax NUMBER(12,2) DEFAULT 0 NOT NULL,
            total_amount NUMBER(12,2) NOT NULL,
            status VARCHAR2(20) DEFAULT ''PENDING'' NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            reviewed_at TIMESTAMP,
            reviewed_by NUMBER,
            review_remarks VARCHAR2(2000),
            CONSTRAINT fk_estimate_request FOREIGN KEY (request_id) REFERENCES service_requests(request_id),
            CONSTRAINT fk_estimate_provider FOREIGN KEY (provider_id) REFERENCES service_providers(provider_id),
            CONSTRAINT fk_estimate_citizen FOREIGN KEY (citizen_id) REFERENCES users(user_id),
            CONSTRAINT fk_estimate_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(user_id),
            CONSTRAINT ck_estimate_status CHECK (status IN (''PENDING'', ''APPROVED'', ''DECLINED'')),
            CONSTRAINT ck_estimate_values CHECK (subtotal > 0 AND tax >= 0 AND total_amount = subtotal + tax)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_ESTIMATE_HISTORY';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_estimate_history (
            history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            estimate_id NUMBER NOT NULL,
            from_status VARCHAR2(20),
            to_status VARCHAR2(20) NOT NULL,
            changed_by NUMBER NOT NULL,
            remarks VARCHAR2(2000),
            changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT fk_estimate_history_estimate FOREIGN KEY (estimate_id) REFERENCES service_estimates(estimate_id),
            CONSTRAINT fk_estimate_history_user FOREIGN KEY (changed_by) REFERENCES users(user_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_indexes WHERE index_name = 'IX_ESTIMATE_REQUEST';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_estimate_request ON service_estimates(request_id, estimate_id)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tab_columns
     WHERE table_name = 'INVOICES' AND column_name = 'SERVICE_REQUEST_ID';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE invoices ADD (service_request_id NUMBER)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tab_columns
     WHERE table_name = 'INVOICES' AND column_name = 'PROVIDER_ID';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE invoices ADD (provider_id NUMBER)';
    END IF;

    SELECT COUNT(*) INTO constraint_count FROM user_constraints WHERE constraint_name = 'FK_INVOICE_SERVICE_REQUEST';
    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE invoices ADD CONSTRAINT fk_invoice_service_request '
            || 'FOREIGN KEY (service_request_id) REFERENCES service_requests(request_id)';
    END IF;

    SELECT COUNT(*) INTO constraint_count FROM user_constraints WHERE constraint_name = 'FK_INVOICE_PROVIDER';
    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE invoices ADD CONSTRAINT fk_invoice_provider '
            || 'FOREIGN KEY (provider_id) REFERENCES service_providers(provider_id)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_indexes WHERE index_name = 'UX_INVOICE_SERVICE_REQUEST';
    IF object_count = 0 THEN
        SELECT COUNT(*) INTO duplicate_count FROM (
            SELECT service_request_id FROM invoices WHERE service_request_id IS NOT NULL
             GROUP BY service_request_id HAVING COUNT(*) > 1
        );
        IF duplicate_count > 0 THEN
            RAISE_APPLICATION_ERROR(-20061,
                'Cannot enforce one service invoice per request: duplicate invoice links must be resolved first.');
        END IF;
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX ux_invoice_service_request ON invoices(service_request_id)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_INVOICE_LINE_ITEMS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_invoice_line_items (
            line_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            invoice_id NUMBER NOT NULL,
            item_description VARCHAR2(1000) NOT NULL,
            quantity NUMBER(8,0) DEFAULT 1 NOT NULL,
            unit_price NUMBER(12,2) NOT NULL,
            total_price NUMBER(12,2) NOT NULL,
            CONSTRAINT fk_service_invoice_line_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id),
            CONSTRAINT ck_service_invoice_line_values CHECK (quantity > 0 AND unit_price >= 0 AND total_price = quantity * unit_price)
        )';
    END IF;
END;
/
