DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_CATEGORIES';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_categories (
            category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            category_name VARCHAR2(100) NOT NULL UNIQUE,
            description VARCHAR2(500),
            is_active NUMBER(1) DEFAULT 1 NOT NULL
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_PROVIDERS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_providers (
            provider_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id NUMBER,
            business_name VARCHAR2(150) NOT NULL,
            contact_name VARCHAR2(100),
            email VARCHAR2(150),
            phone VARCHAR2(30),
            category_id NUMBER,
            description VARCHAR2(1000),
            address VARCHAR2(500),
            city VARCHAR2(100),
            pincode VARCHAR2(20),
            status VARCHAR2(30) DEFAULT ''PENDING'' NOT NULL,
            verification_status VARCHAR2(30) DEFAULT ''UNVERIFIED'' NOT NULL,
            avg_rating NUMBER(3,2) DEFAULT 0 NOT NULL,
            total_jobs NUMBER DEFAULT 0 NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT fk_service_provider_user FOREIGN KEY (user_id) REFERENCES users(user_id),
            CONSTRAINT fk_service_provider_category FOREIGN KEY (category_id) REFERENCES service_categories(category_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'SERVICE_REQUESTS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE service_requests (
            request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            citizen_id NUMBER NOT NULL,
            provider_id NUMBER NOT NULL,
            service_id NUMBER NOT NULL,
            status VARCHAR2(30) DEFAULT ''REQUESTED'' NOT NULL,
            notes VARCHAR2(2000),
            request_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT fk_service_request_citizen FOREIGN KEY (citizen_id) REFERENCES users(user_id),
            CONSTRAINT fk_service_request_provider FOREIGN KEY (provider_id) REFERENCES service_providers(provider_id),
            CONSTRAINT fk_service_request_category FOREIGN KEY (service_id) REFERENCES service_categories(category_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_tables WHERE table_name = 'NOTIFICATIONS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE notifications (
            notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id NUMBER NOT NULL,
            title VARCHAR2(200) NOT NULL,
            message VARCHAR2(2000),
            type VARCHAR2(50),
            link_url VARCHAR2(500),
            is_read NUMBER(1) DEFAULT 0 NOT NULL,
            related_issue_id NUMBER,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            read_at TIMESTAMP,
            CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(user_id),
            CONSTRAINT fk_notification_issue FOREIGN KEY (related_issue_id) REFERENCES community_issues(issue_id)
        )';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_indexes WHERE index_name = 'IX_SERVICE_REQUESTS_PROVIDER';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_service_requests_provider ON service_requests(provider_id, request_date)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM user_indexes WHERE index_name = 'IX_SERVICE_REQUESTS_CITIZEN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_service_requests_citizen ON service_requests(citizen_id, request_date)';
    END IF;
END;
/
